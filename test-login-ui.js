import { chromium } from '@playwright/test';
import express from 'express';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { installAuth, hashPassword } from './auth.js';
const app = express();
app.use(express.json());
installAuth(app, { AUTH_USERNAME: 'ui-admin', AUTH_PASSWORD_HASH: await hashPassword('ui-test-password'), AUTH_COOKIE_SECURE: 'false' });
app.use(express.static('public'));
const server = app.listen(0, '127.0.0.1');
await new Promise(resolve => server.once('listening', resolve));
let browser;
try {
  browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHANNEL ? { channel: process.env.PLAYWRIGHT_CHANNEL } : {}) });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(15000);
  await page.route('https://**/*', route => route.abort());
  const base = `http://127.0.0.1:${server.address().port}`;
  await page.goto(base + '/executive.html');
  assert.ok(page.url().includes('/login.html'));
  await page.locator('.brand img').evaluate(img => img.decode());
  await mkdir('test-results', { recursive: true });
  await page.screenshot({ path: 'test-results/login-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: 'test-results/login-mobile.png', fullPage: true });
  await page.locator('#username').fill('ui-admin');
  await page.locator('#password').fill('wrong');
  await page.locator('#toggle-password').click();
  assert.equal(await page.locator('#password').getAttribute('type'), 'text');
  await page.locator('#submit').click();
  await page.getByText('ชื่อผู้ใช้หรือรหัสผ่านไม่ถูกต้อง', { exact: true }).waitFor();
  await page.locator('#password').fill('ui-test-password');
  await page.locator('#submit').click();
  await page.waitForURL('**/executive.html');
  await page.getByRole('button', { name: '☰ เมนู Workspace' }).click();
  await page.getByRole('button', { name: 'ออกจากระบบ ↗' }).click();
  await page.waitForURL('**/login.html');
  assert.equal((await page.request.get(base + '/api/auth/me')).status(), 401);
  console.log('Desktop/mobile layout, logo, password toggle, invalid login, login redirect and logout passed.');
} finally { await browser?.close(); await new Promise(resolve => { server.close(resolve); server.closeAllConnections(); }); }
